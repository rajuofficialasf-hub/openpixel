export type I18nKey = keyof typeof en

/** Look a key up in `lang`, falling back to English, then to the key itself. */
export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const table = lang === 'bn' ? bn : undefined
  let out = table?.[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v))
    }
  }
  return out
}

/** Plural helper used by count strings: English adds "s", Bengali uses "টি". */
export function plural(lang: Language, n: number): string {
  return lang === 'bn' ? 'টি' : n === 1 ? '' : 's'
}

