/**
 * Bengali / English interface strings (Studio Phase 7).
 *
 * Small hand-written string tables — no i18n library, no
 * machine translation. Rules, per the user's own usage:
 *
 * - Translate the chrome: navigation, headings, buttons, help
 *   text, statuses. Keep tool names and format names English
 *   (PDF, Merge, Compress, OCR, PNG, JPEG…) — that is what
 *   Bengali users expect to see.
 * - Tool descriptions stay English for now: they are long
 *   product copy, not chrome, and translating them badly would
 *   be worse than leaving them.
 * - Every key has an English value; a missing Bengali value
 *   falls back to English, never to a blank string. `t()` is
 *   the single lookup — components never read the tables
 *   directly, so a missing key is a test failure, not a crash.
 *
 * Wiring: `App` wraps the shell in `<I18nProvider
 * language={settings.language}>`; components read strings
 * with `useI18n()`. The stored `settings.language`
 * preference (lib/settings.ts) already exists — this module
 * is what makes the UI actually follow it, including on
 * first load (the provider reads the prop, App reads the
 * stored settings before first paint).
 */
