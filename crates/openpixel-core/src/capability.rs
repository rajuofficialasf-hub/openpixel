use crate::format::ImageFormat;
use serde::{Deserialize, Serialize};

/// What one format can actually do in *this* build.
/// The UI / CLI must generate its options from this — never hard-code
/// a format as supported, and never advertise a capability that is false.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FormatCapability {
    pub format_id: &'static str,
    pub extensions: Vec<&'static str>,
    pub mime_types: Vec<&'static str>,
    pub can_decode: bool,
    pub can_encode: bool,
    pub supports_alpha: bool,
    pub supports_animation: bool,
    pub supports_metadata: bool,
    pub supports_icc: bool,
    pub supports_multiple_frames: bool,
    /// e.g. "image-rs 0.25 (pure Rust)" or "libavif (planned, Phase 3)"
    pub native_dependency: &'static str,
    pub license: &'static str,
    /// Short honest note shown to the user, e.g. "planned" / "preview only".
    pub status: &'static str,
    pub max_dimension: u32,
}

fn cap(
    format: ImageFormat,
    can_decode: bool,
    can_encode: bool,
    supports_alpha: bool,
    supports_animation: bool,
    supports_metadata: bool,
    supports_icc: bool,
    supports_multiple_frames: bool,
    native_dependency: &'static str,
    license: &'static str,
    status: &'static str,
) -> FormatCapability {
    FormatCapability {
        format_id: format.id(),
        extensions: format.extensions().to_vec(),
        mime_types: format.mime_types().to_vec(),
        can_decode,
        can_encode,
        supports_alpha,
        supports_animation,
        supports_metadata,
        supports_icc,
        supports_multiple_frames,
        native_dependency,
        license,
        status,
        // Phase 1 engine-wide limit; per-format limits tighten in Phase 3.
        max_dimension: crate::security::MAX_DIMENSION,
    }
}

