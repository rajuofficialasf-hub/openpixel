pub fn capability(format: ImageFormat) -> Option<FormatCapability> {
    registry().into_iter().find(|c| c.format_id == format.id())
}

pub fn implemented_formats() -> Vec<FormatCapability> {
    registry()
        .into_iter()
        .filter(|c| c.can_decode && c.can_encode)
        .collect()
}
